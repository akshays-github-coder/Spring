package com.cwa.design.patterns.behavioral.observer;

public class ObserverApplication {
/*
    Observer Pattern defines a one-to-many dependency between objects so that when one object changes its state,
    all dependent objects are automatically notified and updated.

    Real-Life Example

YouTube Channel

When you subscribe to a YouTube channel:

YouTube Channel
      |
      |
--------------------
|        |         |
User1   User2    User3

When a new video is uploaded:

New Video Uploaded

All subscribers get notifications automatically.

This is Observer Pattern.

Components
1. Subject (Publisher)

The object being observed.

Example:

YouTube Channel

2. Observer (Subscriber)

Objects interested in updates.

Example:

Subscriber1
Subscriber2
Subscriber3

3. Notification Mechanism

When Subject changes:

notifyObservers()

is called.
*/
}
